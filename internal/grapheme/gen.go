//go:build ignore

// Command gen fetches UCD 17.0.0 files from unicode.org (development time
// only) and writes tables.go: Grapheme_Cluster_Break,
// Extended_Pictographic and Indic_Conjunct_Break. It also saves
// GraphemeBreakTest.txt as test data. Run by go generate.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const base = "https://www.unicode.org/Public/17.0.0/ucd/"

func fetch(path string) []byte {
	resp, err := http.Get(base + path)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", path, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return b
}

type rng struct {
	lo, hi rune
	val    string
}

// parse reads "XXXX(..YYYY)? ; field[; field]" lines; pick selects the
// value from the fields (empty to skip the line). Adjacent ranges with equal
// values are merged.
func parse(data []byte, pick func(fields []string) string) []rng {
	var out []rng
	s := bufio.NewScanner(bytes.NewReader(data))
	for s.Scan() {
		line, _, _ := strings.Cut(s.Text(), "#")
		if strings.TrimSpace(line) == "" {
			continue
		}
		fields := strings.Split(line, ";")
		for i := range fields {
			fields[i] = strings.TrimSpace(fields[i])
		}
		v := pick(fields)
		if v == "" {
			continue
		}
		lo, hi, _ := strings.Cut(fields[0], "..")
		l, _ := strconv.ParseUint(lo, 16, 32)
		h := l
		if hi != "" {
			h, _ = strconv.ParseUint(hi, 16, 32)
		}
		out = append(out, rng{rune(l), rune(h), v})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].lo < out[j].lo })
	var merged []rng
	for _, r := range out {
		if n := len(merged); n > 0 && merged[n-1].val == r.val && merged[n-1].hi+1 == r.lo {
			merged[n-1].hi = r.hi
			continue
		}
		merged = append(merged, r)
	}
	return merged
}

func emit(w *bytes.Buffer, name string, rs []rng, conv func(string) string) {
	fmt.Fprintf(w, "var %s = []rangeVal{\n", name)
	for _, r := range rs {
		fmt.Fprintf(w, "\t{0x%04X, 0x%04X, %s},\n", r.lo, r.hi, conv(r.val))
	}
	fmt.Fprintf(w, "}\n\n")
}

func main() {
	var w bytes.Buffer
	w.WriteString("// Code generated by gen.go from UCD 17.0.0. DO NOT EDIT.\n\npackage grapheme\n\n")
	gcb := parse(fetch("auxiliary/GraphemeBreakProperty.txt"), func(f []string) string { return f[1] })
	emit(&w, "graphemeBreak", gcb, func(v string) string { return "gcb" + strings.ReplaceAll(v, "_", "") })
	ep := parse(fetch("emoji/emoji-data.txt"), func(f []string) string {
		if f[1] == "Extended_Pictographic" {
			return "1"
		}
		return ""
	})
	emit(&w, "extPict", ep, func(string) string { return "1" })
	incb := parse(fetch("DerivedCoreProperties.txt"), func(f []string) string {
		if f[1] == "InCB" && len(f) > 2 {
			return f[2]
		}
		return ""
	})
	emit(&w, "inCB", incb, func(v string) string { return "inCB" + v })
	src, err := format.Source(w.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("testdata/GraphemeBreakTest.txt", fetch("auxiliary/GraphemeBreakTest.txt"), 0o644); err != nil {
		log.Fatal(err)
	}
}
