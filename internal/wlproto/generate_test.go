package wlproto

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"testing"
)

// directive is one `//go:generate wayland-scanner MODE XML OUT` line.
type directive struct{ mode, xml, out string }

func directives(t *testing.T) []directive {
	t.Helper()
	src, err := os.ReadFile("generate.go")
	if err != nil {
		t.Fatal(err)
	}
	re := regexp.MustCompile(`(?m)^//go:generate wayland-scanner (\S+) (\S+) (\S+)$`)
	var ds []directive
	for _, m := range re.FindAllStringSubmatch(string(src), -1) {
		ds = append(ds, directive{m[1], m[2], m[3]})
	}
	return ds
}

// Every protocol XML has both a client header and its interface tables.
func TestEveryProtocolIsGenerated(t *testing.T) {
	xmls, err := filepath.Glob("protocols/*.xml")
	if err != nil {
		t.Fatal(err)
	}
	if len(xmls) == 0 {
		t.Fatal("no protocol XML files in protocols/")
	}
	ds := directives(t)
	for _, xml := range xmls {
		name := strings.TrimSuffix(filepath.Base(xml), ".xml")
		for _, want := range []directive{
			{"client-header", xml, name + "-client-protocol.h"},
			{"private-code", xml, name + "-protocol.c"},
		} {
			if !slices.Contains(ds, want) {
				t.Errorf("generate.go lacks //go:generate wayland-scanner %s %s %s",
					want.mode, want.xml, want.out)
			}
		}
	}
}

// The committed glue is what `go generate` writes. Scanners of other
// versions write other bytes, so the check runs only with the version that
// generated the committed files.
func TestCommittedGlueMatchesTheScanner(t *testing.T) {
	scanner, err := exec.LookPath("wayland-scanner")
	if err != nil {
		t.Skip("wayland-scanner is not installed")
	}
	out, err := exec.Command(scanner, "--version").CombinedOutput()
	if err != nil {
		t.Fatalf("wayland-scanner --version: %v\n%s", err, out)
	}
	installed := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(string(out)), "wayland-scanner"))
	dir := t.TempDir()
	for _, d := range directives(t) {
		committed, err := os.ReadFile(d.out)
		if err != nil {
			t.Fatal(err)
		}
		header := "/* Generated by wayland-scanner " + installed + " */\n"
		if !bytes.HasPrefix(committed, []byte(header)) {
			t.Skipf("%s was not generated by wayland-scanner %s", d.out, installed)
		}
		fresh := filepath.Join(dir, d.out)
		if out, err := exec.Command(scanner, d.mode, d.xml, fresh).CombinedOutput(); err != nil {
			t.Fatalf("wayland-scanner %s %s: %v\n%s", d.mode, d.xml, err, out)
		}
		want, err := os.ReadFile(fresh)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(committed, want) {
			t.Errorf("%s is stale: run go generate ./internal/wlproto", d.out)
		}
	}
}
